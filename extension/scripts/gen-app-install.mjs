// Generates src/data/appInstall.ts — the shipped app ids plus which of them are required or
// opt-in, read straight from each app's meta.ts (the single source of truth).
//
// Why a generated map rather than importing metaIndex: the installed-apps rule (lib/installedApps.ts)
// runs in CONTENT SCRIPTS too, and metaIndex eagerly bundles every meta.ts — names, accents,
// marketing copy. Measured, that costs several kB on writer.js, shipped into every page the user
// visits, for a rule that only needs three id lists.
//
// Same approach as www/scripts/gen-apps.mjs: each meta.ts is dependency-free (it
// imports only the pure `defineMeta` helper), so we bundle them with esbuild and read the real
// values rather than regex-scraping. Only SHIPPED apps (those with an index.ts) are included, so
// WIP scaffolds don't leak in. Runs automatically via the prebuild / pretypecheck hooks.
//
//   node scripts/gen-app-install.mjs
import { readdirSync, existsSync, writeFileSync, statSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { format, resolveConfig } from 'prettier';

const HERE = dirname(fileURLToPath(import.meta.url));
const APPS_DIR = join(HERE, '..', 'src', 'apps');
const OUT = join(HERE, '..', 'src', 'data', 'appInstall.ts');

// A shipped app = a directory with BOTH meta.ts and an index.{ts,js}.
const ids = readdirSync(APPS_DIR).filter(
  (d) =>
    statSync(join(APPS_DIR, d)).isDirectory() &&
    existsSync(join(APPS_DIR, d, 'meta.ts')) &&
    (existsSync(join(APPS_DIR, d, 'index.ts')) || existsSync(join(APPS_DIR, d, 'index.js'))),
);

// Bundle all metas into one module and evaluate it (they import only the pure
// defineMeta helper, so this is safe outside the browser).
const entry =
  ids.map((id, i) => `import m${i} from ${JSON.stringify(join(APPS_DIR, id, 'meta.ts'))}`).join('\n') +
  `\nexport const metas = [${ids.map((_, i) => `m${i}`).join(', ')}]`;
const bundled = await build({
  stdin: { contents: entry, resolveDir: APPS_DIR, loader: 'ts' },
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'node',
  logLevel: 'silent',
});
const mod = await import('data:text/javascript;base64,' + Buffer.from(bundled.outputFiles[0].text).toString('base64'));

const appIds = mod.metas
  .filter(Boolean)
  .map((m) => m.id)
  .sort((a, b) => a.localeCompare(b));

// Required apps are infrastructure: always installed, never uninstallable (#176). Derived
// from meta.ts and emitted here because lib/installedApps.ts — which is bundled into the content
// scripts — must reach the same verdict as the new tab's model. Two places deciding "is this app
// installed?" is how the clipboard gate once drifted.
const required = mod.metas
  .filter(Boolean)
  .filter((m) => m.required)
  .map((m) => m.id)
  .sort((a, b) => a.localeCompare(b));

// Opt-in apps ship uninstalled (`optIn: true` in meta.ts): added on demand.
const optIn = mod.metas
  .filter(Boolean)
  .filter((m) => m.optIn)
  .map((m) => m.id)
  .sort((a, b) => a.localeCompare(b));

const list = (ids) => `[${ids.map((id) => `'${id}'`).join(', ')}]`;

const file = `// GENERATED by scripts/gen-app-install.mjs from src/apps/*/meta.ts — DO NOT EDIT.
// Re-run \`npm run gen:app-install\` (auto-runs on build/typecheck) after adding an app or
// changing its \`required\` / \`optIn\` flag. CI asserts this file is in sync with the metas.
//
// Kept tiny because lib/installedApps.ts is bundled into content scripts, which run on every
// page the user visits.

// Every shipped app id.
export const APP_IDS: string[] = ${list(appIds)};

// Infrastructure, not tools: always installed, never uninstallable (\`required: true\` in
// meta.ts). AnubisDB is the console over the one shared on-device database — uninstalling it
// would not remove the data, only the user's control of it.
export const REQUIRED_APP_IDS: string[] = ${list(required)};

// Apps that ship uninstalled (\`optIn: true\` in meta.ts) — the user adds them when they want them.
export const OPT_IN_APP_IDS: string[] = ${list(optIn)};
`;

mkdirSync(dirname(OUT), { recursive: true });
// Formatted with the repo's own Prettier config, so the committed file is format-clean and the
// CI regenerate-and-diff check does not fight `prettier --check`.
writeFileSync(OUT, await format(file, { ...(await resolveConfig(OUT)), filepath: OUT }));
console.log(`gen-app-install: ${appIds.length} apps → src/data/appInstall.ts`);
