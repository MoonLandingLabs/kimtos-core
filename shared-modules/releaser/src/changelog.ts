// CHANGELOG.md, and the compiled copy the extension renders.
//
// Ported VERBATIM from the old `scripts/gen-changelog.mjs`. The only addition is a `root`,
// so the tests can run against a fixture directory instead of the real repo.
//
// WHY THE NOTES ARE BUNDLED, NOT FETCHED. The extension used to pull the changelog from a
// public GitHub repo, which stopped working the moment that repo went private (an
// extension in a user's browser is an ANONYMOUS client: it gets a 404). Bundling is the
// better design anyway — the notes for version X ship WITH version X, because a release IS
// a new build — and it removes a network call from a product whose whole promise is that
// it makes almost none.
//
// CHANGELOG.md is the source of truth (human-readable, reviewable in a PR).
// extension/src/data/changelog.ts is generated from it; do not hand-edit that file.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { escapeRegExp } from './notes.js';
import { units, readUnitChangelog } from './units.js';
import prettier from 'prettier';

export interface ChangelogEntry {
  version: string;
  date: string;
  /** Markdown. */
  body: string;
}

const MARKER = '<!-- releases below; newest first -->';

const mdPath = (root: string): string => join(root, 'CHANGELOG.md');
const tsPath = (root: string): string => join(root, 'extension', 'src', 'data', 'changelog.ts');
const appChangelogsPath = (root: string): string => join(root, 'extension', 'src', 'data', 'appChangelogs.ts');

/** Every release in CHANGELOG.md, newest first. */
export function readChangelog(root = process.cwd()): ChangelogEntry[] {
  return parse(readFileSync(mdPath(root), 'utf8'));
}

function parse(md: string): ChangelogEntry[] {
  const entries: ChangelogEntry[] = [];
  // Split on the release headings rather than regex-matching each block: JS has no \Z, and
  // "up to the next ## or end of file" is exactly what a split gives you for free.
  const parts = md.split(/^## /m).slice(1); // drop everything before the first release
  for (const part of parts) {
    const m = part.match(/^v(\d\S*)\s+[—-]\s+(\S+)\s*\n([\s\S]*)$/);
    if (m) entries.push({ version: m[1]!, date: m[2]!, body: m[3]!.trim() });
  }
  return entries;
}

/**
 * Add a release section to CHANGELOG.md, newest first, under the marker.
 * Throws if the version is already there — a release is not something to do twice.
 */
export function addRelease(version: string, notes: string, root = process.cwd()): void {
  const v = version.replace(/^v/, '');
  const md = readFileSync(mdPath(root), 'utf8');

  if (new RegExp(`^## v${escapeRegExp(v)}\\b`, 'm').test(md)) {
    throw new Error(`CHANGELOG.md already has a v${v} section.`);
  }

  const date = new Date().toISOString().slice(0, 10);
  const section = `\n## v${v} — ${date}\n\n${notes.trim()}\n`;
  writeFileSync(mdPath(root), md.replace(MARKER, `${MARKER}\n${section}`));
}

/** Compile CHANGELOG.md into the data the extension renders. Returns the entry count. */
export async function compile(root = process.cwd()): Promise<number> {
  const entries = readChangelog(root);
  const out = tsPath(root);

  const ts =
    `// GENERATED by @kimtos/releaser from CHANGELOG.md — do not edit by hand.\n` +
    `//\n` +
    `// The release notes are BUNDLED, not fetched: the notes for a version ship with that\n` +
    `// version, and the extension makes no network call to show them.\n\n` +
    `export interface ChangelogEntry {\n` +
    `  version: string;\n` +
    `  date: string;\n` +
    `  /** Markdown. */\n` +
    `  body: string;\n` +
    `}\n\n` +
    `/** Newest first. */\n` +
    `export const CHANGELOG: ChangelogEntry[] = ${JSON.stringify(entries, null, 2)};\n`;

  // Format it the way the extension formats everything else, so the committed file passes
  // `format:check` like the other generated files do. Emitting "nearly right" TS and
  // leaving CI to complain is not a saving.
  const config = await prettier.resolveConfig(out);
  writeFileSync(out, await prettier.format(ts, { ...config, filepath: out }));
  return entries.length;
}

/**
 * Compile every app's CHANGELOG.md into extension/src/data/appChangelogs.ts — the file the
 * extension imports to render per-app release notes and to DERIVE each app's version (its
 * newest entry). Returns the app count.
 *
 * This is the exact generation extension/scripts/gen-app-changelogs.mjs runs on every build
 * (`prebuild`/`pretypecheck`). It lives here so the RELEASE path regenerates it too: cutting
 * a release bumps every touched app's CHANGELOG.md, and if this derived file is not
 * regenerated in the same commit the tag declares app versions its own committed data no
 * longer matches (#889). The output is byte-identical to the standalone script, so there is
 * one generator, not two that can drift.
 *
 * Throws — loud, not silent — if an app has no CHANGELOG.md: a missing changelog means the
 * app has no version, and a silent fallback to "1.0.0" is precisely the bug this replaces.
 */
export async function compileAppChangelogs(root = process.cwd()): Promise<number> {
  const apps = units(root).filter((u) => u.kind === 'app');

  const entries: Record<string, ReturnType<typeof readUnitChangelog>> = {};
  for (const app of apps) {
    const releases = readUnitChangelog(app.dir);
    if (releases.length) entries[app.id] = releases;
  }

  const missing = apps.filter((a) => !entries[a.id]).map((a) => a.id);
  if (missing.length) {
    throw new Error(
      `Apps with no CHANGELOG.md: ${missing.join(', ')}\n` +
        `Every app must have one — its newest entry is the app version.`,
    );
  }

  const out = appChangelogsPath(root);
  const ts =
    `// GENERATED by extension/scripts/gen-app-changelogs.mjs from each app's CHANGELOG.md —\n` +
    `// do not edit by hand.\n` +
    `//\n` +
    `// An app's CHANGELOG.md owns its version: the newest entry IS the version. There is no\n` +
    `// \`version\` field in meta.ts, on purpose — a second place is a place to drift, and it did.\n\n` +
    `export interface AppRelease {\n` +
    `  version: string;\n` +
    `  date: string;\n` +
    `  /** Clean one-line bullets — no marker, no issue ref, no comments. */\n` +
    `  lines: string[];\n` +
    `}\n\n` +
    `/** Every app's releases, newest first. */\n` +
    `export const APP_CHANGELOGS: Record<string, AppRelease[]> = ${JSON.stringify(entries, null, 2)};\n\n` +
    `/** The app's version — its newest release. The only place this is declared. */\n` +
    `export const appVersion = (id: string): string => APP_CHANGELOGS[id]?.[0]?.version ?? '';\n\n` +
    '/** The app\'s first-release date — its OLDEST entry. Drives the "New" badge (#1114): an app\n' +
    ' *  is new for NEW_APP_DAYS from this date (see `isNewApp` in @kimtos/config). Empty when the\n' +
    ' *  app has no changelog, which reads as "not new". */\n' +
    `export const appFirstReleased = (id: string): string => APP_CHANGELOGS[id]?.at(-1)?.date ?? '';\n\n` +
    `/** The app's releases, newest first. */\n` +
    `export const appReleases = (id: string): AppRelease[] => APP_CHANGELOGS[id] ?? [];\n`;

  mkdirSync(dirname(out), { recursive: true });
  const config = await prettier.resolveConfig(out);
  writeFileSync(out, await prettier.format(ts, { ...config, filepath: out }));
  return apps.length;
}

/**
 * Run the repo's own prettier over each file, in place, so the files a release WRITES are
 * committed already matching `prettier --check .`.
 *
 * addRelease() and releaseUnit() assemble Markdown by string concatenation with no
 * formatting pass, so the committed CHANGELOG.md failed the repo-wide Formatting gate and
 * turned main red after every release until someone reformatted it by hand (#889). Rather
 * than hand-roll formatting, we run the same prettier the rest of the repo is held to —
 * config resolved per file, so a workspace override still applies. Missing files are
 * skipped; a file already clean is left untouched.
 */
export async function formatFiles(files: string[]): Promise<void> {
  for (const file of files) {
    if (!existsSync(file)) continue;
    const src = readFileSync(file, 'utf8');
    const config = await prettier.resolveConfig(file);
    const formatted = await prettier.format(src, { ...config, filepath: file });
    if (formatted !== src) writeFileSync(file, formatted);
  }
}
