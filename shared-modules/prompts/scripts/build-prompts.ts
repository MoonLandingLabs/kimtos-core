// Inline every prompts/*.md into src/generated.ts so the SDK ships the prompt
// text baked in — no runtime fs, no bundler-specific `?raw`. Run before tsc.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const promptsDir = join(here, '..', 'prompts');
const outFile = join(here, '..', 'src', 'generated.ts');

const files = readdirSync(promptsDir)
  .filter((f) => f.endsWith('.md'))
  .sort();
const body = files
  .map((f) => `  ${JSON.stringify(basename(f, '.md'))}: ${JSON.stringify(readFileSync(join(promptsDir, f), 'utf8'))},`)
  .join('\n');
const out = `// AUTO-GENERATED by scripts/build-prompts.mjs — do not edit.\n// Source of truth: shared-modules/prompts/prompts/*.md\nexport const RAW: Record<string, string> = {\n${body}\n};\n`;
writeFileSync(outFile, out);
console.log(`[@kimtos/prompts] inlined ${files.length} prompt(s): ${files.map((f) => basename(f, '.md')).join(', ')}`);
