// Generates www/data/apps.ts from the extension's per-app metadata
// (extension/src/apps/*/meta.ts). Each meta.ts is dependency-free, so we bundle
// them with esbuild and read the real values — no fragile source parsing. Apps
// with a `marketing` block appear on the site; add one and it shows up here on
// the next dev/build. Runs automatically via the predev/prebuild npm hooks.
//
//   node scripts/gen-apps.mjs
import { readdirSync, existsSync, writeFileSync, statSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'
import { format, resolveConfig } from 'prettier'
import { unitFirstReleased } from '@kimtos/releaser'

const HERE = dirname(fileURLToPath(import.meta.url))
const APPS_DIR = join(HERE, '..', '..', 'extension', 'src', 'apps')
const OUT = join(HERE, '..', 'data', 'apps.ts')

const WORDS = [
  'zero',
  'one',
  'two',
  'three',
  'four',
  'five',
  'six',
  'seven',
  'eight',
  'nine',
  'ten',
  'eleven',
  'twelve',
  'thirteen',
  'fourteen',
  'fifteen',
  'sixteen',
  'seventeen',
  'eighteen',
  'nineteen',
  'twenty',
]
const word = (n) => WORDS[n] ?? String(n)

// Discover every app that ships a meta.ts.
const ids = readdirSync(APPS_DIR).filter(
  (d) => statSync(join(APPS_DIR, d)).isDirectory() && existsSync(join(APPS_DIR, d, 'meta.ts')),
)

// Bundle all metas into one module and evaluate it (they import only the pure
// defineMeta helper, so this is safe outside the browser).
const entry =
  ids.map((id, i) => `import m${i} from ${JSON.stringify(join(APPS_DIR, id, 'meta.ts'))}`).join('\n') +
  `\nexport const metas = [${ids.map((_, i) => `m${i}`).join(', ')}]`
const bundled = await build({
  stdin: { contents: entry, resolveDir: APPS_DIR, loader: 'ts' },
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'node',
  logLevel: 'silent',
})
const mod = await import('data:text/javascript;base64,' + Buffer.from(bundled.outputFiles[0].text).toString('base64'))

const apps = mod.metas
  .filter((m) => m && m.marketing)
  .sort((a, b) => (a.order ?? 100) - (b.order ?? 100) || a.name.localeCompare(b.name))
  .map((m) => ({
    id: m.id,
    name: m.name,
    c: m.accent,
    tech: m.marketing.tech,
    desc: m.marketing.desc,
    points: m.marketing.points,
    featured: Boolean(m.marketing.featured) || undefined,
    // First-release date — the OLDEST entry in the app's own CHANGELOG.md, the same source
    // the extension derives its version from (#132). The "New" badge counts 30 days from
    // this (`isNewApp` in @kimtos/config, #1114). Omitted when an app has no changelog, which
    // the badge reads as "not new". No new field on meta.ts, on purpose — that is the drift
    // `version` was deleted to avoid.
    firstReleased: unitFirstReleased(join(APPS_DIR, m.id)) || undefined,
  }))

const featured = apps.filter((a) => a.featured).length

const file = `// GENERATED by scripts/gen-apps.mjs from extension/src/apps/*/meta.ts — DO NOT EDIT.
// Add or change an app's meta.ts, then re-run \`npm run gen:apps\` (auto-runs on dev/build).

export interface MarketingApp {
  id: string
  name: string
  /** Accent colour (hex). */
  c: string
  tech: string
  desc: string
  /** Three short highlights for the flip-card back. */
  points: [string, string, string]
  /** Shown up-front in the landing grid (the rest hide behind "+N more"). */
  featured?: boolean
  /** First-release date (ISO, from the app's CHANGELOG.md). Drives the "New" badge; absent
   *  when the app has no changelog. */
  firstReleased?: string
}

export const APPS: MarketingApp[] = ${JSON.stringify(apps, null, 2)}

/** Live counts, so copy never drifts from the catalog. */
export const APP_STATS = { total: ${apps.length}, featured: ${featured} } as const

/** Spelled-out counts for prose. */
export const APP_WORDS = {
  total: '${word(apps.length)}',
} as const
`

// Format with Prettier before writing, so `gen:apps` output matches the committed
// file exactly. JSON.stringify emits quoted keys/double quotes that the repo's
// format pass would rewrite; an unformatted write drifts from git the moment
// anyone runs `make format` (#559). (The admin generator has a CI in-sync assert
// that turns that drift into a red build; www has none yet, but the same rule.)
const cfg = (await resolveConfig(OUT)) ?? {}
const formatted = await format(file, { ...cfg, parser: 'typescript' })

writeFileSync(OUT, formatted)
console.log(`gen-apps: ${apps.length} apps (all free, ${featured} featured) → data/apps.ts`)
